// Validates the commit message against Conventional Commits.
// Rewrites it from the branch name when possible, and marks "wip" commits with [skip ci].
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const keywords = ['build', 'chore', 'ci', 'docs', 'feat', 'fix', 'perf', 'refactor', 'revert', 'style', 'test'];
const conventionRegex = new RegExp(`^(${keywords.join('|')})(\\([\\w\\-\\s]+\\))?!?\\s?:\\s[a-z].*`);
const typedPrefixRegex = new RegExp(`^(${keywords.join('|')})(\\([^)]*\\))?!?\\s?:`);

const file = process.argv[2];
const message = readFileSync(file, 'utf8').split('\n')[0];

// Merge, revert and fixup commits generated by git itself are let through
if (/^(Merge |Revert "|fixup! |squash! |\[skip ci\])/.test(message) || conventionRegex.test(message)) {
	process.exit(0);
}

if (/^wip/i.test(message)) {
	writeFileSync(file, `[skip ci] ${message}\n`);
	console.log('WIP commit: "[skip ci]" prefix added');
	process.exit(0);
}

// The type is the branch segment matching a keyword, the scope is the segment right after it:
// "laucoin/chore/deps" -> "chore(deps): message", "docs/registry/02-functional" -> "docs(registry): message"
const branch = execSync('git branch --show-current').toString().trim();
const segments = branch.split('/');
const typeIndex = segments.findIndex((segment) => keywords.includes(segment));
const keyword = segments[typeIndex];
const scope = segments[typeIndex + 1];
if (keyword && /^[a-z]/.test(message) && !typedPrefixRegex.test(message)) {
	for (const candidate of [`${keyword}(${scope}): ${message}`, `${keyword}: ${message}`]) {
		if (conventionRegex.test(candidate)) {
			writeFileSync(file, `${candidate}\n`);
			console.log(`Commit message rewritten from branch "${branch}": ${candidate}`);
			process.exit(0);
		}
	}
}

console.error(`\n✖ Commit message "${message}" does not follow Conventional Commits.\n
  Expected: <type>(<scope>): <summary>   e.g. docs(registry): add cache ADR
  Types:    ${keywords.join(', ')}
  The type and the first letter of the summary must be lowercase; "!" before ":" marks a breaking change.
  Or start with "wip" to skip CI.\n`);
process.exit(1);
